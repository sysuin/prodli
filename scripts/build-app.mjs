#!/usr/bin/env node
// Builds the ProdLi web app (same React code as the extension, web storage)
// for app.prodli.com into artifacts/prodli-api/app-dist, which the prodli-api
// Worker serves next to /api.
//
// Also writes the offline files: a web app manifest (installable on phones
// and desktops) and a service worker that keeps every built file cached, so
// the app opens and works without a connection (sync catches up later).

import { execSync } from "node:child_process";
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "artifacts/prodli-api/app-dist");

execSync(`pnpm exec vite build --config vite.config.ts --outDir "${outDir}" --emptyOutDir`, {
  cwd: path.join(root, "artifacts/prodli"),
  stdio: "inherit",
  env: { ...process.env, NODE_ENV: "production", BASE_PATH: "/", VITE_PRODLI_API: "same-origin" },
});

// Files the extension/marketing site use but the app doesn't need offline.
const skip = /^(store-assets\/|promo\.html$|opengraph\.jpg$|sw\.js$|_headers$|_redirects$)|\.woff$/; // .woff: every supported browser uses .woff2
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    const rel = path.relative(outDir, full).split(path.sep).join("/");
    if (statSync(full).isDirectory()) walk(full);
    else if (!skip.test(rel)) files.push(rel);
  }
};
walk(outDir);
files.sort();

const hash = createHash("sha256");
for (const f of files) hash.update(f).update(readFileSync(path.join(outDir, f)));
const version = hash.digest("hex").slice(0, 12);

writeFileSync(
  path.join(outDir, "manifest.webmanifest"),
  JSON.stringify(
    {
      name: "ProdLi",
      short_name: "ProdLi",
      description: "Notes, to-dos, habits, Pomodoro, meetings and time tracking — synced with the ProdLi extension.",
      start_url: "/",
      scope: "/",
      display: "standalone",
      background_color: "#F0E6D2",
      theme_color: "#000000",
      // Phones: "Share → ProdLi" from any app opens Quick add (src/lib/capture.ts).
      share_target: { action: "/", method: "GET", params: { title: "title", text: "text", url: "url" } },
      // Installed web app: "Open with ProdLi" for these files (read in the browser, never uploaded).
      file_handlers: [
        {
          action: "/?section=files",
          accept: {
            "text/markdown": [".md", ".markdown"],
            "text/csv": [".csv"],
            "text/tab-separated-values": [".tsv"],
            "application/json": [".json"],
            "application/x-ndjson": [".jsonl", ".ndjson"],
            "text/plain": [".txt", ".log"],
          },
        },
      ],
      shortcuts: [
        { name: "Today", url: "/?section=today" },
        { name: "Quick add", url: "/?quickadd=1" },
      ],
      icons: [
        { src: "/icon-192.png", sizes: "192x192", type: "image/png", purpose: "any maskable" },
        { src: "/icon-512.png", sizes: "512x512", type: "image/png", purpose: "any maskable" },
      ],
    },
    null,
    2,
  ),
);

const precache = ["/", ...files.filter((f) => f !== "index.html").map((f) => `/${f}`), "/manifest.webmanifest"];
writeFileSync(
  path.join(outDir, "sw.js"),
  `// ProdLi web app service worker (generated by scripts/build-app.mjs — don't edit).
// Keeps this version's files cached so the app opens offline. /api is never cached.
const VERSION = ${JSON.stringify(version)};
const CACHE = "prodli-app-" + VERSION;
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("prodli-app-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  const url = new URL(req.url);
  if (req.method !== "GET" || url.origin !== self.location.origin || url.pathname.startsWith("/api/")) return;
  if (req.mode === "navigate") {
    // Fresh page when online (picks up new versions), cached app when offline.
    event.respondWith(fetch(req).catch(() => caches.match("/", { cacheName: CACHE })));
    return;
  }
  // Built files have content hashes in their names: cache first.
  event.respondWith(caches.match(req, { cacheName: CACHE }).then((hit) => hit || fetch(req)));
});
`,
);

// Security headers for the app's pages and files (served by Cloudflare's static
// assets without running the Worker; /api responses get theirs from the Worker).
// The CSP allows only ProdLi itself plus Google sign-in and Google Fonts.
const csp = [
  "default-src 'self'",
  "script-src 'self' https://accounts.google.com/gsi/client",
  "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com https://accounts.google.com/gsi/style",
  "font-src 'self' https://fonts.gstatic.com data:",
  "img-src 'self' data: blob: https://*.googleusercontent.com",
  "connect-src 'self' https://accounts.google.com/gsi/ https://www.googleapis.com/calendar/",
  "frame-src https://accounts.google.com/gsi/",
  "worker-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join("; ");
writeFileSync(
  path.join(outDir, "_headers"),
  `/*
  Content-Security-Policy: ${csp}
  X-Content-Type-Options: nosniff
  Referrer-Policy: strict-origin-when-cross-origin
  X-Frame-Options: DENY
  Cross-Origin-Opener-Policy: same-origin-allow-popups
  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()
  Strict-Transport-Security: max-age=31536000; includeSubDomains

/assets/*
  Cache-Control: public, max-age=31536000, immutable
`,
);

console.log(`\n✓ Web app ready in ${path.relative(root, outDir)}/ (offline cache ${version}, ${precache.length} files)`);
