#!/usr/bin/env node
// Builds the phone's note editor (main.tsx) into one HTML page, wrapped as a JS
// module the app imports (src/ui/noteEditorHtml.js), the way TenTap ships its
// own editor. Run after changing the note blocks (artifacts/prodli
// sections/editor/noteSchema.ts or phoneExtensions.ts):
//
//   pnpm --filter @workspace/prodli-mobile run build:editor
//
// The page is TenTap's own HTML shell (its styles and boot marker) with this
// bundle inlined. TipTap resolves to the same installed files from TenTap's
// source and from ProdLi's blocks, so there's one copy of it (and of React).

import { mkdtempSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { editorSourceHash } from "./sourceHash.mjs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "vite";

const here = path.dirname(fileURLToPath(import.meta.url));
const app = path.resolve(here, "..");
const require = createRequire(path.join(app, "package.json"));
const tentap = path.dirname(require.resolve("@10play/tentap-editor/package.json"));
const out = mkdtempSync(path.join(tmpdir(), "prodli-note-editor-"));

await build({
  configFile: false,
  logLevel: "warn",
  root: here,
  define: { "process.env.NODE_ENV": JSON.stringify("production") },
  esbuild: { jsx: "automatic" },
  // TipTap resolves to the same installed files from TenTap and from ProdLi's blocks; React comes from this app.
  resolve: { dedupe: ["react", "react-dom"] },
  build: {
    outDir: out,
    emptyOutDir: true,
    target: "es2019",
    minify: true,
    modulePreload: false,
    rollupOptions: { input: path.join(here, "main.tsx"), output: { format: "es", inlineDynamicImports: true, entryFileNames: "editor.js" } },
  },
});

const js = readFileSync(path.join(out, readdirSync(out).find((f) => f.endsWith(".js"))), "utf8").replace(/<\/script/gi, "<\\/script");
const shell = readFileSync(path.join(tentap, "src/simpleWebEditor/index.html"), "utf8");
const tag = '<script type="module" src="/index.tsx"></script>';
if (!shell.includes(tag) || !shell.includes("<!--TENTAP_BOOT-->")) throw new Error("TenTap's editor page changed: update build.mjs");
// The bundle goes in the head like TenTap's (module scripts run after the page is parsed).
// (A function replacement: the minified code contains "$" sequences a string replacement would expand.)
const html = shell.replace(tag, () => "").replace("</head>", () => `  <script type="module">${js}</script>\n  </head>`);
rmSync(out, { recursive: true, force: true });

const target = path.join(app, "src/ui/noteEditorHtml.js");
writeFileSync(target, `// @ts-nocheck\n/* eslint-disable */\n// Generated by editor-web/build.mjs (pnpm --filter @workspace/prodli-mobile run build:editor). Don't edit.\nexport const editorSourceHash = ${JSON.stringify(editorSourceHash())};\nexport const editorHtml = ${JSON.stringify(html)};\n`);
writeFileSync(path.join(app, "src/ui/noteEditorHtml.d.ts"), "/** The phone's note editor page (editor-web/build.mjs). */\nexport declare const editorHtml: string;\n/** A hash of the files it was built from (tests check it's up to date). */\nexport declare const editorSourceHash: string;\n");
console.log(`✓ src/ui/noteEditorHtml.js (${Math.round(html.length / 1024)} KB)`);
